"""Shared helpers for the layout tools: layer names, cell classification, hierarchy walks."""
import re
import xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path

import klayout.db as kdb

RUNS = Path(__file__).resolve().parents[1]
LYP = RUNS.parent / "ws-run2" / "lyp" / "gf180mcu.lyp"
RETICLES = {"ws-run1": RUNS / "layout" / "G801.oas", "ws-run2": RUNS / "layout" / "G802.oas"}

STDCELL_RE = re.compile(r"gf180mcu_(?:fd|as|osu)_(?:sc|ex)_(\w+?)__(\w+)")
FILL_TYPES = ("fill", "endcap", "filltie", "fillcap", "tap", "antenna", "diode", "tiel", "tieh", "decap")
SRAM_RE = re.compile(r"(gf180mcu_\w+?_ip_sram__sram\d+x\d+[a-z0-9]*)$")
IO_RE = re.compile(r"(gf180mcu_\w+?_io__\w+)")
# Cells added by the fill and seal-ring steps of the wafer.space flow, not by the designer.
FILL_RE = re.compile(r"(_fill_cell|^(METAL\d|COMP|POLY2|Metal\d|Poly2)_FILL|^sealring)", re.I)


def is_via_cell(name):
    """Via arrays generated by the router (OpenROAD names them VIA_via1_2_...)."""
    return base_name(name).startswith("VIA_")


def is_fill_cell(name):
    return bool(FILL_RE.search(base_name(name)))


def layer_names():
    """Map (layer, datatype) -> name from the GF180MCU layer properties file."""
    names = {}
    for props in ET.parse(LYP).getroot().iter("properties"):
        # The source reads "Metal1 34/0@1"; unnamed layers are just "1/222@1".
        m = re.match(r"(?:(\S+)\s+)?(\d+)/(\d+)", props.findtext("source") or "")
        if m and m.group(1):
            names[(int(m.group(2)), int(m.group(3)))] = m.group(1)
    return names


def base_name(name):
    """Cell name without the suffix KLayout adds when it de-duplicates names ($1, $2...)."""
    return name.split("$")[0]


def classify(name):
    """Return ('std', library, type, is_fill) / ('sram', macro) / ('io', cell) / None."""
    base = base_name(name)
    m = SRAM_RE.search(base)
    if m:
        return ("sram", m.group(1))
    m = STDCELL_RE.search(base)
    if m:
        cell_type = m.group(2)
        return ("std", m.group(1), cell_type, cell_type.startswith(FILL_TYPES))
    m = IO_RE.search(base)
    if m:
        return ("io", m.group(1))
    return None


def flat_counts(cell, leaf):
    """Count flattened placements below `cell` of every cell for which leaf(cell) is not None.

    Leaves are not descended into. Returns Counter keyed by leaf(cell).
    """
    cache = {}

    def walk(c):
        ci = c.cell_index()
        if ci in cache:
            return cache[ci]
        counts = Counter()
        key = leaf(c)
        if key is not None:
            counts[key] = 1
        else:
            for inst in c.each_inst():
                n = inst.cell_inst.size()
                for k, v in walk(inst.cell).items():
                    counts[k] += v * n
        cache[ci] = counts
        return counts

    return walk(cell)


def hier_shape_counts(layout, cell):
    """Flattened shape count per layer index below `cell`, without flattening."""
    cache = {}
    layer_indexes = list(layout.layer_indexes())

    def walk(c):
        ci = c.cell_index()
        if ci in cache:
            return cache[ci]
        counts = Counter()
        for li in layer_indexes:
            n = c.shapes(li).size()
            if n:
                counts[li] = n
        for inst in c.each_inst():
            n = inst.cell_inst.size()
            for k, v in walk(inst.cell).items():
                counts[k] += v * n
        cache[ci] = counts
        return counts

    return walk(cell)


def um_box(box):
    return [round(box.left, 3), round(box.bottom, 3), round(box.right, 3), round(box.top, 3)]


def load(path):
    layout = kdb.Layout()
    layout.read(str(path))
    return layout


def pick_cell(layout, name=None):
    if name:
        cell = layout.cell(name)
        if cell is None:
            raise SystemExit("no cell named %r" % name)
        return cell
    tops = sorted(layout.top_cells(), key=lambda c: -c.bbox().area())
    return tops[0]
